int main(void) {
  uint8_t payload[GXFP_PAYLOAD_MAX] = {0}, record[GXFP_RECORD_MAX] = {0};
  size_t payload_size = gxfp_payload(payload, wrapper, seed8);
  size_t record_size = gxfp_record(record, payload, payload_size);
  if (payload_size != sizeof(expected_payload) ||
      memcmp(payload, expected_payload, sizeof(expected_payload))) {
    fprintf(stderr, "payload mismatch\n");
    return 1;
  }
  if (record_size != sizeof(expected_record) ||
      memcmp(record, expected_record, sizeof(expected_record))) {
    fprintf(stderr, "record mismatch\n");
    return 1;
  }
  uint8_t frame[GXFP_FRAGMENT_MAX];
  size_t size = gxfp_fragment(frame, record, 252, 1);
  if (size != 256 || memcmp(frame, "\xcc\xf2\x01\x00", 4) ||
      memcmp(frame + 4, record, 252)) {
    fprintf(stderr, "first fragment mismatch\n");
    return 1;
  }
  size = gxfp_fragment(frame, record + 252, 4, 2);
  if (size != 8 || frame[2] != 2 || memcmp(frame + 4, record + 252, 4)) {
    fprintf(stderr, "final fragment mismatch\n");
    return 1;
  }
  if (gxfp_fragment(frame, record, 253, 1) != 0 ||
      gxfp_fragment(frame, record, 0, 1) != 0) {
    fprintf(stderr, "oversize fragment accepted\n");
    return 1;
  }
  puts("Payload tests passed: empty host-cache TLV, E0/A0 framing, checksums "
       "and ITE fragment layout.");
  return 0;
}
